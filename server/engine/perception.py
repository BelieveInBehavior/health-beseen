"""
Perception — 从用户自然语言输入中抽取症状关键词。
MVP 版本使用关键词匹配；production 可接入 LLM NER。
"""

from __future__ import annotations

# 症状词库（用于从用户输入中抽取已知症状标签）
SYMPTOM_LEXICON: list[tuple[str, list[str]]] = [
    ("呼吸困难", ["呼吸困难", "呼吸急促", "喘不过气", "无法呼吸", "呼吸不畅"]),
    ("胸闷", ["胸闷", "胸痛", "心悸", "心跳异常", "心慌"]),
    ("高热", ["高烧", "39度", "40度", "高热", "体温39", "体温40"]),
    ("发热", ["发烧", "发热", "低烧", "37.5", "38度", "体温偏高"]),
    ("过敏反应", ["过敏", "荨麻疹", "喉咙肿", "喉头水肿"]),
    ("出血", ["出血", "便血", "咯血", "吐血", "血尿"]),
    ("意识障碍", ["意识模糊", "神志不清", "昏迷", "抽搐", "癫痫"]),
    ("恶心呕吐", ["恶心", "呕吐", "想吐", "干呕", "反胃"]),
    ("腹泻", ["腹泻", "拉肚子", "水样便"]),
    ("注射部位反应", ["注射部位", "注射红肿", "注射疼痛", "肿痛"]),
    ("皮肤反应", ["皮疹", "红疹", "皮肤痒", "皮肤干燥", "水泡", "破溃", "脱皮"]),
    ("疲劳", ["疲劳", "乏力", "没力气", "体力下降", "容易累"]),
    ("食欲下降", ["食欲下降", "食欲差", "不想吃", "吃不下", "厌食"]),
    ("头痛", ["头痛", "头疼", "偏头痛"]),
    ("失眠", ["失眠", "睡眠差", "睡不好", "入睡困难"]),
    ("神经病变", ["手脚麻木", "指尖麻", "感觉异常", "麻木"]),
]


def extract_symptoms(text: str) -> list[str]:
    """从输入文本抽取症状标签列表。"""
    found: list[str] = []
    for label, triggers in SYMPTOM_LEXICON:
        if any(t in text for t in triggers):
            found.append(label)
    return found
